import assert from 'node:assert/strict';
import {runTrueShapeNesting,editNestingPlacement,refreshNestingSheet} from '../src/manufacturing/NestingEngine.js';
import {optimizeNesting,betterNesting,nestingScore} from '../src/manufacturing/NestingOptimizer.js';
import {createDefaultState} from '../src/core/state.js';
import {createNestingImportedTab,getActiveNestingImportedItems,applyNestingPartOverrides,syncActiveNestingTab,switchNestingTab} from '../src/manufacturing/NestingTabs.js';
const rect=(id,w,h)=>({id,label:id,outer:[{x:0,y:0},{x:w,y:0},{x:w,y:h},{x:0,y:h}],holes:[],areaMm2:w*h,materialGroup:'metal'});
const items=[rect('background',2300,600),...Array.from({length:14},(_,i)=>rect('part'+i,90+i*8,180))];
const state=createDefaultState(),n=state.nesting;const tab=createNestingImportedTab(n,{filename:'fixture.pdf',items});
const config={sheetWidthMm:3000,sheetHeightMm:1500,clearanceMm:5,kerfMm:.4,optimizationBudgetMs:800};
const baseline=runTrueShapeNesting(items,{...config,quickImport:true});
const result=optimizeNesting(items,config);assert.equal(result.unplaced.length,0);assert(!betterNesting(baseline,result));assert(result.optimization.attempts>0);
n.sheets=result.sheets;n.partOverrides={background:{deleted:true},part0:{scale:2}};
const edited=applyNestingPartOverrides(getActiveNestingImportedItems(n),n);assert.equal(edited.length,14);assert.equal(edited.find(x=>x.id==='part0').areaMm2,items[1].areaMm2*4);
syncActiveNestingTab(n);switchNestingTab(n,'design');switchNestingTab(n,tab.id);assert(n.partOverrides.background.deleted);
const a=n.sheets[0].placements.find(x=>x.id==='part0');const old=a.areaMm2;assert(editNestingPlacement(a,'scale',2));assert.equal(a.areaMm2,old*4);refreshNestingSheet(n.sheets[0],5.4);
console.log('✓ Nesting independent edits persist through repack; optimization no worse than fast baseline; contour dimensions and statistics synchronized',nestingScore(result));

import {nextNestingSelection,deleteNestingParts} from '../src/manufacturing/NestingSelection.js';
import {renderNestingCenter} from '../src/ui/CentralWorkspaces.js';
import {renderNestingSvg} from '../src/ui/NestingView.js';
const order=['a','b','c','d','e'];
let selection=nextNestingSelection(order,[],null,'b');
assert.deepEqual(selection.ids,['b']);
selection=nextNestingSelection(order,selection.ids,selection.anchor,'d',{toggle:true});
assert.deepEqual(selection.ids,['b','d']);
selection=nextNestingSelection(order,selection.ids,selection.anchor,'b',{range:true});
assert.deepEqual(selection.ids,['b','c','d']);
selection=nextNestingSelection(order,selection.ids,selection.anchor,'e',{range:true,addRange:true});
assert.deepEqual(selection.ids,['b','c','d','e']);
selection=nextNestingSelection(order,selection.ids,selection.anchor,'c',{toggle:true});
assert.deepEqual(selection.ids,['b','d','e']);
assert.deepEqual(nextNestingSelection(order,selection.ids,selection.anchor,null).ids,[]);
const selectionState=createDefaultState();
const source=order.map(id=>rect(id,50,40));
createNestingImportedTab(selectionState.nesting,{filename:'multi.svg',items:source});
selectionState.nesting.sheets=runTrueShapeNesting(source,{sheetWidthMm:600,sheetHeightMm:300,quickImport:true}).sheets;
const sh=selectionState.nesting.sheets[0];
assert.equal(sh.placements.length,5);
sh.placements.find(p=>p.id==='c').locked=true;
const html=renderNestingCenter(selectionState,{activeSheetIdx:0,selectedPlacementIds:['a','b','c']});
assert.equal((html.match(/data-cws-check/g)||[]).length,5);
assert.equal((html.match(/data-cws-delete/g)||[]).length,5);
assert.equal((html.match(/aria-selected="true"/g)||[]).length,3);
assert.ok(html.includes('Seçilenleri Sil (2)'));
assert.equal((renderNestingSvg(sh,new Set(['a','b','c'])).match(/nest-picked/g)||[]).length,3);
assert.deepEqual(deleteNestingParts(selectionState.nesting,0,['b'],5),['b']);
assert.ok(sh.placements.some(p=>p.id==='a'));
assert.deepEqual(deleteNestingParts(selectionState.nesting,0,['a','c'],5),['a']);
assert.ok(sh.placements.some(p=>p.id==='c'));
assert.equal(sh.placements.length,3);
assert.equal(sh.usedAreaMm2,6000);
assert.equal(applyNestingPartOverrides(getActiveNestingImportedItems(selectionState.nesting),selectionState.nesting).length,3);
assert.equal(source.length,5);
syncActiveNestingTab(selectionState.nesting);
console.log('✓ Nesting Ctrl / Shift range and checkbox selection, SVG highlighting, isolated row deletion, batch deletion, locked protection and repack persistence');
