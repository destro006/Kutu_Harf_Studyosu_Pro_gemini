import assert from 'node:assert/strict';
import { DocumentManager } from '../src/core/DocumentManager.js';
import { captureObjectClipboard, pasteObjectClipboard } from '../src/core/ObjectClipboard.js';
import { serializeProject, deserializeProject } from '../src/core/projectSerializer.js';

const manager = new DocumentManager();
const originId = manager.activeDocId;
const source = manager.getActiveStore().get();
const letter = source.objects[0];
letter.text = 'MERHABA';
letter.fileWidthMm = 8;
letter.faceMaterial = 'aynaAltin';
letter.lightingMode = 'front';
letter.xMm = 55;
const customLayer = { id: 'layer_custom_src', name: 'Müşteri Logoları', visible: true, locked: false, exportable: true };
source.pages[0].layers.push(customLayer);
const originalObjectId = letter.id;
source.objects.push({ ...letter, id: 'logo_copy_source', name: 'Müşteri Logosu', layerId: customLayer.id, kind:'logo', polygonsMm:[{outer:[{x:0,y:0},{x:80,y:0},{x:80,y:50},{x:0,y:50}],holes:[]}], groupId:'source_group' });
letter.groupId='source_group';
source.selectedIds=[originalObjectId,'logo_copy_source'];
const packet = captureObjectClipboard(source, { sourceDocumentId:originId });
assert.equal(packet.objects.length,2);
assert.equal(packet.layers.length,2);

const targetDoc = manager.newDocument('Proje İki');
assert.equal(manager.documents.length,2);
assert.equal(manager.activeDocId,targetDoc.id);
const target = manager.getActiveStore().get();
assert.notEqual(target,source);
assert.equal(target.objects.length,1);
const dstObjectId = target.objects[0].id;
const added = pasteObjectClipboard(target,packet,{offsetMm:0});
assert.equal(added.length,2);
assert.equal(target.objects.length,3);
assert.equal(target.selectedIds.length,2);
assert.equal(target.objects[1].text,'MERHABA');
assert.equal(target.objects[1].xMm,55);
assert.equal(target.objects[1].fileWidthMm,8);
assert.equal(target.objects[1].faceMaterial,'aynaAltin');
assert.equal(target.objects[1].lightingMode,'front');
assert.notEqual(target.objects[1].id, originalObjectId);
assert.equal(target.objects[2].kind,'logo');
assert.equal(target.objects[2].polygonsMm[0].outer.length,4);
assert.equal(target.objects[1].groupId,target.objects[2].groupId);
assert.notEqual(target.objects[1].groupId,'source_group');
assert(target.pages[0].layers.some(l=>l.id===target.objects[2].layerId && l.name==='Müşteri Logoları'));
assert.notEqual(target.objects[2].layerId,'layer_custom_src');
assert.equal(target.objects[0].id,dstObjectId);
assert.equal(source.objects.length,2);
assert.equal(source.objects[0].text,'MERHABA');

const secondPaste = pasteObjectClipboard(target,packet,{offsetMm:40});
assert.equal(secondPaste.length,2);
assert.equal(target.objects.length,5);
assert.equal(target.pages[0].layers.filter(l=>l.name==='Müşteri Logoları').length,1);
assert.equal(target.objects[3].xMm,95);
assert.notEqual(target.objects[3].id,target.objects[1].id);
assert.notEqual(target.objects[3].groupId,target.objects[1].groupId);

assert.equal(manager.switchDocument(originId),true);
assert.equal(manager.getActiveStore().get().objects.length,2);
assert.equal(manager.switchDocument(targetDoc.id),true);
assert.equal(manager.getActiveStore().get().objects.length,5);
const serialized=serializeProject(target);
assert.equal(deserializeProject(serialized).objects.length,5);
console.log('✓ Sekme yönetimi / sekmeler arası kopyala-yapıştır: 16 kapsamlı doğrulama geçti');
