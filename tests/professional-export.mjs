import assert from 'node:assert/strict';
import THREE from '../src/vendor/three.js';
import {collectManufacturingContours,collectNestingContours,prepareVectorPage,generateVectorPdf,generateVectorEps,generateVectorHpgl} from '../src/export/Professional2DExport.js';
import {collectSignTriangles,writeStlAscii,writeStlBinary,writeObjMtl,writePly,writeGlb,writeGltf,write3mf} from '../src/export/Professional3DExport.js';
import {EXPORT_FORMATS,getExportFormat,formatSupportsSource} from '../src/export/ExportFormatCatalog.js';
import {rgbaToBmp} from '../src/export/RasterExport.js';
const ring=[{x:0,y:0},{x:100,y:0},{x:100,y:80},{x:0,y:80}];
const hole=[{x:20,y:20},{x:60,y:20},{x:60,y:50},{x:20,y:50}];
const c=collectManufacturingContours([{label:'A',objectId:'a',offsetXMm:20,offsetYMm:-10,exportContours:{outer:[{outer:ring,holes:[hole]}],file:[],acrylic:[]}}]);
assert.equal(c.length,2);
assert.equal(c[0].points[0].x,20);
assert.equal(c[0].points[0].y,-10);
const page=prepareVectorPage(c);
assert.equal(page.widthMm,110);
assert.equal(page.heightMm,90);
const pdf=generateVectorPdf(c);
assert.equal(new TextDecoder().decode(pdf.subarray(0,8)),'%PDF-1.4');
const pdfText=new TextDecoder().decode(pdf);
assert(pdfText.includes('/MediaBox [0 0 311.811'));
const start=Number(pdfText.match(/startxref\n(\d+)/)?.[1]);
assert.equal(pdfText.slice(start,start+4),'xref');
assert.equal((pdfText.match(/h S/g)||[]).length,2);
const eps=generateVectorEps(c);
assert(eps.startsWith('%!PS-Adobe-3.0 EPSF-3.0'));
assert(eps.includes('%%BoundingBox: 0 0'));
assert(eps.includes('closepath stroke'));
const hpgl=generateVectorHpgl(c);
assert(hpgl.startsWith('IN;\nSP1;'));
assert(hpgl.includes('PU800,-400;')); // 20mm,-10mm at 40 units/mm
assert(hpgl.endsWith('SP0;\n'));
const sheet=collectNestingContours([{widthMm:500,placements:[{outer:ring,holes:[hole],label:'A'}]}]);
assert.equal(sheet.length,2);
const group=new THREE.Group();
const body=new THREE.Group();body.userData.layerId='a';group.add(body);
const mesh=new THREE.Mesh(new THREE.BoxGeometry(1,.6,.1),new THREE.MeshStandardMaterial({color:0xf4c776,roughness:0.3,metalness:0.8}));
mesh.position.set(1,2,0);body.add(mesh);
const other=new THREE.Group();other.userData.layerId='b';group.add(other);
const otherMesh=new THREE.Mesh(new THREE.BoxGeometry(.3,.3,.1),new THREE.MeshStandardMaterial({color:0x80aacf}));other.add(otherMesh);
const selected=collectSignTriangles(group,['a']);
assert.equal(selected.length,1);
assert.equal(selected[0].triangles.length,12);
assert.equal(collectSignTriangles(group).length,2);
assert.throws(()=>collectSignTriangles(group,[]));
const stl=writeStlBinary(selected);
assert.equal(new DataView(stl.buffer).getUint32(80,true),12);
assert.equal(stl.length,84+12*50);
assert(writeStlAscii(selected).includes('solid Kutu_Harf_Studyosu_mm'));
const {obj,mtl}=writeObjMtl(selected);
assert(obj.includes('mtllib'));
assert(obj.includes('usemtl material_0'));
assert(obj.includes('v 500')); // translated cube in millimeters
assert(mtl.includes('newmtl material_0'));
const ply=writePly(selected);
assert(ply.includes('element face 12'));
assert(ply.includes('element vertex 36'));
const glb=writeGlb(selected);
assert.equal(new DataView(glb.buffer).getUint32(0,true),0x46546c67);
assert.equal(new DataView(glb.buffer).getUint32(4,true),2);
assert.equal(new DataView(glb.buffer).getUint32(8,true),glb.length);
const jsonLength=new DataView(glb.buffer).getUint32(12,true);
const gltfDoc=JSON.parse(new TextDecoder().decode(glb.slice(20,20+jsonLength)).trim());
assert.equal(gltfDoc.asset.version,'2.0');
assert.equal(gltfDoc.meshes.length,1);
assert.equal(gltfDoc.accessors[0].count,36);
assert.equal(gltfDoc.materials[0].pbrMetallicRoughness.metallicFactor,0.8);
const gltf=JSON.parse(writeGltf(selected));
assert(gltf.buffers[0].uri.startsWith('data:application/octet-stream;base64,'));
const mf=write3mf(selected);
assert.equal(new DataView(mf.buffer).getUint32(0,true),0x04034b50);
assert.equal(new DataView(mf.buffer).getUint32(mf.length-22,true),0x06054b50);
console.log('✓ True vector PDF/EPS/HPGL + actual OBJ/STL/PLY/glTF/GLB/3MF 3D exports verified');

assert(EXPORT_FORMATS.length >= 35);
for(const id of ['pdf','svg','eps','ps','dxf','plt','png','transparentPng','jpg','webp','bmp','glb','gltf','obj','stl','stla','ply','3mf','gcode','csv','json']) assert.equal(getExportFormat(id)?.ready,true);
for(const id of ['cdr','ai','dwg','fbx','usd','usdz','step','blend','psd','tiff']) assert.equal(getExportFormat(id)?.ready,false);
assert.equal(formatSupportsSource('glb','nestingActive'),false);
assert.equal(formatSupportsSource('pdf','nestingActive'),true);
