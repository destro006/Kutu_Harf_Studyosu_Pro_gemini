import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createDefaultState } from '../src/core/state.js';
import { MATERIAL_PRESETS } from '../src/render/MaterialLibrary.js';
import { applySurfaceMaterialPreset, getDisplayedSurfaceMaterial } from '../src/core/MaterialActions.js';
import { getExportSelection } from '../src/export/ExportScope.js';
import { computeQualityPixelRatio, QUALITY_PROFILES } from '../src/render/SignEngine.js';
const state=createDefaultState();
const first=state.objects[0];
first.constructionType='fileli';
first.faceMaterial='aynaAltin';
first.fileMaterial='aynaAltin';
const second={...structuredClone(first),id:'second',constructionType:'metal',faceMaterial:'aynaAltin',fileMaterial:null};
const locked={...structuredClone(first),id:'locked',locked:true};
state.objects=[first,second,locked];
state.selectedIds=[first.id];
state.materials.ralCode='RAL 9005';
assert.equal(applySurfaceMaterialPreset(state,'roseGold'),1);
assert.equal(first.faceMaterial,'roseGold');
assert.equal(first.fileMaterial,'roseGold');
assert.equal(first.sideMaterial,'roseGold');
assert.equal(state.materials.ralCode,'');
assert.equal(second.faceMaterial,'aynaAltin');
assert.equal(getDisplayedSurfaceMaterial(state),'roseGold');
state.selectedIds=[second.id];
assert.equal(applySurfaceMaterialPreset(state,'aynaKrom'),1);
assert.equal(second.faceMaterial,'aynaKrom');
assert.equal(first.fileMaterial,'roseGold');
assert.equal(getDisplayedSurfaceMaterial(state),'aynaKrom');
state.selectedIds=[];
assert.equal(applySurfaceMaterialPreset(state,'satenAltin'),2);
assert.equal(first.fileMaterial,'satenAltin');
assert.equal(second.faceMaterial,'satenAltin');
assert.equal(locked.faceMaterial,'aynaAltin');
assert.equal(getDisplayedSurfaceMaterial(state),state.materials.faceId);
state.selectedIds=[first.id];
state.materials.ralCode='RAL 3020';
assert.equal(applySurfaceMaterialPreset(state,'fircaliAltin'),1);
assert.equal(state.materials.ralCode,'');
assert.equal(first.fileMaterial,'fircaliAltin');
assert.equal(MATERIAL_PRESETS[first.fileMaterial].brushed,true);
const metrics=[{objectId:first.id,label:'first'},{objectId:second.id,label:'second'}];
const scoped=getExportSelection(state,metrics,true);
assert.equal(scoped.objectCount,1);
assert.equal(scoped.metrics.length,1);
assert.equal(scoped.metrics[0].objectId,first.id);
assert.notEqual(scoped.state,state);
assert.equal(scoped.state.objects.length,1);
assert.equal(state.objects.length,3);
assert.equal(getExportSelection(state,metrics,false).metrics.length,2);
state.selectedIds=[];
assert.equal(getExportSelection(state,metrics,true).objectCount,0);
assert(computeQualityPixelRatio('performance',1,1200,800)<computeQualityPixelRatio('balanced',1,1200,800));
assert(computeQualityPixelRatio('balanced',1,1200,800)<computeQualityPixelRatio('high',1,1200,800));
assert(computeQualityPixelRatio('high',1,1200,800)<computeQualityPixelRatio('ultra',1,1200,800));
assert(computeQualityPixelRatio('ultra',3,4000,3000)<=Math.sqrt(8_000_000/(4000*3000))+1e-7);
assert(QUALITY_PROFILES.ultra.shadowSize>QUALITY_PROFILES.balanced.shadowSize);
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
for(const id of ['btnOpenExport','exportDialog','exportFormat','exportOnlySelected','exportResolution','btnRunExport','qualityStatus']) assert(html.includes('id="'+id+'"'));
const main=fs.readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
assert(main.includes('onExport: openExportDialog'));
assert(main.includes('await studioExport(format,'));
assert(main.includes('runProfessionalExport({'));
assert(main.includes('updateProfessionalExportDialogState()'));
assert(main.includes('applySurfaceMaterialPreset(s,b.dataset.faceMat)'));
const shortcuts=fs.readFileSync(new URL('../src/cad/Shortcuts.js',import.meta.url),'utf8');
assert(shortcuts.includes("ctrl && key === 'e'"));
console.log('✓ Material card selection, RAL/metal exclusive, actual GPU quality, selected export and Ctrl+E UI');
